import 'dart:convert';
import 'dart:typed_data';
import 'package:crypto/crypto.dart';
import 'package:image/image.dart' as img;
import '../models/processor_models.dart';

/// An identity card exchanged out-of-band (QR code or share sheet) that lets
/// a receiver trust a sender's Ed25519 public key before verifying documents.
class IdentityCard {
  const IdentityCard({
    required this.name,
    required this.publicKey,
    this.fingerprint,
  });

  final String name;
  final String publicKey;
  final String? fingerprint;
}

class ForensicUtils {
  /// Calculates a stable hash of the image pixels, optionally excluding bits
  /// used for steganography.
  static String calculateForensicHash(img.Image image,
      {bool excludeAllLSB = false, bool excludeRedLSB = false}) {
    return calculateForensicHashBytes(image,
            excludeAllLSB: excludeAllLSB, excludeRedLSB: excludeRedLSB)
        .toString();
  }

  /// Calculates a stable hash of the image pixels, returning raw bytes.
  static Digest calculateForensicHashBytes(img.Image image,
      {bool excludeAllLSB = false, bool excludeRedLSB = false}) {
    final int width = image.width;
    final int height = image.height;
    final buffer = Uint8List(width * height * 3); // R, G, B
    var idx = 0;
    for (final frame in image.frames) {
      for (int y = 0; y < height; y++) {
        for (int x = 0; x < width; x++) {
          final pixel = frame.getPixel(x, y);
          var r = pixel.r.toInt();
          var g = pixel.g.toInt();
          var b = pixel.b.toInt();

          if (excludeAllLSB) {
            r &= 0xFE;
            g &= 0xFE;
            b &= 0xFE;
          } else if (excludeRedLSB) {
            r &= 0xFE; // Clear LSB of Red (where verification link lives)
          }

          buffer[idx++] = r;
          buffer[idx++] = g;
          buffer[idx++] = b;
        }
      }
      break; // Only hash the first frame
    }
    return sha256.convert(buffer);
  }

  static String generateVerificationLink(
      String sig, String cHash, String sHash) {
    return 'securemark://verify?v=1&s=${base64Url.encode(utf8.encode(sig))}&c=$cHash&o=$sHash';
  }

  /// Builds a scannable identity-card URI carrying the sender name, public
  /// key and key fingerprint. The `securemark://identity` scheme keeps the
  /// payload self-describing so the receiver can tell it apart from
  /// receive/verify links.
  static String generateIdentityCard(
      String name, String publicKey, String fingerprint) {
    return 'securemark://identity?v=1'
        '&n=${Uri.encodeComponent(name)}'
        '&pk=${Uri.encodeComponent(publicKey)}'
        '&fp=$fingerprint';
  }

  /// Parses an identity card from scanned or pasted data. Accepts the
  /// `securemark://identity` URI, the legacy JSON format
  /// (`{"name": ..., "publicKey": ...}`) and a bare public key, so cards
  /// generated by older app versions keep working. Returns null when the
  /// data is not an identity card at all (e.g. a receive link).
  static IdentityCard? parseIdentityCard(String data) {
    final trimmed = data.trim();
    if (trimmed.isEmpty) return null;
    try {
      if (trimmed.startsWith('securemark://identity')) {
        final uri = Uri.parse(trimmed.replaceFirst('securemark://', 'http://'));
        final publicKey = uri.queryParameters['pk'];
        if (publicKey == null || publicKey.isEmpty) return null;
        return IdentityCard(
          name: uri.queryParameters['n'] ?? 'New Identity',
          publicKey: publicKey,
          fingerprint: uri.queryParameters['fp'],
        );
      }
      // Other URI schemes (receive/verify links) are not identity cards.
      if (trimmed.contains('://')) return null;
      if (trimmed.startsWith('{')) {
        final dynamic decoded = jsonDecode(trimmed);
        if (decoded is Map) {
          final publicKey = decoded['publicKey'];
          if (publicKey is String && publicKey.isNotEmpty) {
            return IdentityCard(
              name: (decoded['name'] as String?) ?? 'New Identity',
              publicKey: publicKey,
            );
          }
        }
        return null;
      }
      // Bare public key (scanned directly, no wrapper).
      return IdentityCard(name: 'New Identity', publicKey: trimmed);
    } catch (_) {
      return null;
    }
  }

  static VerificationResult? verifyDeepLink(
      String link, String currentContentHash, String currentSourceHash) {
    try {
      if (!link.startsWith('securemark://verify?v=1&')) return null;
      final uri = Uri.parse(link.replaceFirst('securemark://', 'http://'));
      final sigBase64 = uri.queryParameters['s'];
      final originalContentHash = uri.queryParameters['c'];
      final originalSourceHash = uri.queryParameters['o'];

      if (sigBase64 == null ||
          originalContentHash == null ||
          originalSourceHash == null) {
        return null;
      }

      final author = utf8.decode(base64Url.decode(sigBase64));
      final isContentAuthentic = originalContentHash == currentContentHash;
      final isSourceAuthentic = originalSourceHash == currentSourceHash;

      return VerificationResult(
        isContentAuthentic: isContentAuthentic,
        isSourceAuthentic: isSourceAuthentic,
        author: author,
        timestamp: DateTime.now(),
      );
    } catch (_) {
      return null;
    }
  }
}
